my_dictionary = {
    "name": "Mia",
    "age": 2,
    "animal": "cat"
}

# Display the value for a specific key
print(my_dictionary["name"])

# Remove a key and its associated value
my_dictionary.pop("age")

# Display all keys
print(my_dictionary.keys())

# Display all values
print(my_dictionary.values())

my_dictionary["age"] = 3
print(my_dictionary)

